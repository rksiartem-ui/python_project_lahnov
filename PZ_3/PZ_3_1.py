# Проверить истинность высказывания: «Данное число является четным двузначным».
while True:
    try:
        n = int(input("Введите двузначное чётное число: "))
        break # ввод удался
    except ValueError:
        print("Надо ввести целое число")
if 9 < n <= 99 and n % 2 == 0:
    print("Истинно: данное число чётное двузначное")
else:
    print("Высказывание ложно")