# Дано трехзначное число. Вывести число, полученное при прочтении исходного числа справа налево.
while True:
    try:
        n = int(input("Введите трёхзначное число: "))
        if 100 <= n <= 999:
            break
        print("Ошибка: число должно быть трёхзначным (100-999).")
    except ValueError:
        print("Ошибка: нужно ввести целое число.")
a = n // 100
b = n // 10 % 10
c = n % 10
print(c * 100 + b * 10 + a)